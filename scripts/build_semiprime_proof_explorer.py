#!/usr/bin/env python3
"""Generate the static semiprime algorithm explorer, without invoking Lean.

Input statuses retain each publication packet's source/evidence scope.
Stage order is curated prose, never an elaborated dependency graph. --check is
read-only and compares every generated byte, including local source snapshots.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "docs/semiprime-proof-explorer"
METADATA = SITE / "metadata.json"
MODULE_STATUSES = {"finalized-machine", "proved-math", "draft", "legacy-unclassified"}
STAGE_STATUSES = MODULE_STATUSES | {"partial", "mixed", "open", "proved", "finalized"}
STATIC = ("index.html", "source.html", "release.js", "metadata.json", "assets/style.css", "assets/app.js", "assets/source.js")


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def json_bytes(data) -> bytes:
    return (json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode()


def safe_path(root: Path, value: str) -> Path:
    path = Path(value)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"Expected a repository-relative path: {value}")
    result = (root / path).resolve()
    if not result.is_relative_to(root.resolve()) or not result.is_file():
        raise ValueError(f"Missing or escaping source/evidence path: {value}")
    return result


def mask_lean(text: str) -> str:
    """Mask nested comments and strings while retaining authored line numbers."""
    out = list(text)
    i, depth, string = 0, 0, False
    while i < len(text):
        if depth:
            if text.startswith("/-", i):
                out[i:i + 2] = "  "; depth += 1; i += 2; continue
            if text.startswith("-/", i):
                out[i:i + 2] = "  "; depth -= 1; i += 2; continue
            if text[i] != "\n": out[i] = " "
            i += 1; continue
        if string:
            if text[i] == "\\" and i + 1 < len(text):
                out[i] = " "; out[i + 1] = "\n" if text[i + 1] == "\n" else " "; i += 2; continue
            if text[i] == '"': string = False
            if text[i] != "\n": out[i] = " "
            i += 1; continue
        if text.startswith("/-", i): out[i:i + 2] = "  "; depth = 1; i += 2; continue
        if text.startswith("--", i):
            end = text.find("\n", i)
            if end < 0: end = len(text)
            out[i:end] = " " * (end - i); i = end; continue
        if text[i] == '"': out[i] = " "; string = True
        i += 1
    return "".join(out)


def declarations(text: str) -> list[dict]:
    """Source-parsed authored declarations; not compiled names or proof edges."""
    blocks: list[tuple[str, list[str]]] = []
    rows = []
    pattern = re.compile(r"^\s*(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|noncomputable|unsafe|partial)\s+)*(def|theorem|lemma|abbrev|structure|class|inductive|opaque|axiom|instance)\s+([^\s(:{\[=]+)")
    for number, line in enumerate(mask_lean(text).splitlines(), 1):
        namespace = re.match(r"^\s*namespace\s+([\w.']+)", line)
        section = re.match(r"^\s*(?:noncomputable\s+)?section(?:\s|$)", line)
        if namespace: blocks.append(("namespace", namespace[1].split(".")))
        elif section: blocks.append(("section", []))
        elif re.match(r"^\s*end(?:\s|$)", line):
            if blocks: blocks.pop()
        found = pattern.match(line)
        if not found: continue
        kind, name = found.groups()
        if name in {"where", ":="}: continue
        names = [p for category, parts in blocks if category == "namespace" for p in parts]
        full = name if name.startswith("RiemannGaussian.") else ".".join(names + [name])
        rows.append({"name": full, "kind": kind, "line": number})
    return rows


def evidence_records(value):
    if isinstance(value, dict):
        if isinstance(value.get("path"), str) and isinstance(value.get("sha256"), str): yield value
        for item in value.values(): yield from evidence_records(item)
    elif isinstance(value, list):
        for item in value: yield from evidence_records(item)


def build(root: Path = ROOT, site: Path = SITE) -> dict[Path, bytes]:
    meta_path = site / "metadata.json"
    meta = json.loads(meta_path.read_bytes())
    packet = safe_path(root, meta["publication_packet"] + "/inventory.json").parent
    inventory_bytes = (packet / "inventory.json").read_bytes()
    progress_bytes = (packet / "progress.json").read_bytes()
    inventory, progress = json.loads(inventory_bytes), json.loads(progress_bytes)
    if inventory.get("schema_version") != 1 or progress.get("schema_version") != 1:
        raise ValueError("Unsupported publication schema")
    complete = progress.get("full_goal_complete", progress.get("research_goal", {}).get("full_goal_complete"))
    if complete is not False or progress.get("research_goal", {}).get("status") != "paused":
        raise ValueError("This publication must preserve the paused goal and OPEN full theorem")
    if progress.get("curated_stage_order_not_lean_dependencies") is not True:
        raise ValueError("Stage order must be explicitly curated, not claimed as Lean dependencies")
    if not progress.get("stages"): raise ValueError("No algorithm stages")
    outputs = {site / "data/publication-inventory.json": inventory_bytes, site / "data/publication-progress.json": progress_bytes}
    evidence, local_evidence = {}, {}
    for record in evidence_records(inventory):
        # Absolute historical origins may be retained as provenance, not live links.
        if Path(record["path"]).is_absolute(): continue
        path = safe_path(root, record["path"])
        actual = digest(path.read_bytes())
        if actual != record["sha256"]: raise ValueError(f"Evidence/source hash mismatch: {record['path']}")
        if record["path"].startswith("RiemannGaussian/"): continue
        evidence[record["path"]] = actual
        name = f"{actual[:16]}-{path.name}"
        local_evidence[record["path"]] = f"data/evidence/{name}"
        outputs[site / "data/evidence" / name] = path.read_bytes()
    groups, memberships = [], {}
    for group in inventory.get("groups", []):
        identifier = group.get("id") or group.get("group")
        if not identifier: raise ValueError("Evidence group missing id")
        candidates = [r["path"] for r in evidence_records(group) if r["path"] in local_evidence]
        if not candidates: raise ValueError(f"Evidence group lacks a copied manifest: {identifier}")
        manifest = json.loads(safe_path(root, group.get("path", candidates[0])).read_bytes())
        reported = manifest.get("status", "")
        if not isinstance(reported, str) or not reported.startswith("FINAL"):
            raise ValueError(f"Group is not a recorded FINAL component: {identifier}")
        if group.get("reported_status", reported) != reported:
            raise ValueError(f"Recorded group status differs from copied manifest: {identifier}")
        memberships[identifier] = {m["module"]: m["sha256"] for m in group.get("modules", [])}
        groups.append({"id": identifier, "title": group.get("title", identifier),
                       "local_evidence": local_evidence[candidates[0]] if candidates else "data/audit.json"})
    if len({g["id"] for g in groups}) != len(groups): raise ValueError("Duplicate evidence group ids")
    group_ids = {g["id"] for g in groups}
    modules, snapshots, source_pins = [], {format(i, "x"): {} for i in range(16)}, {}
    for row in inventory["modules"]:
        module, path_string, status = row["module"], row["path"], row["status"]
        if status not in MODULE_STATUSES: raise ValueError(f"Unknown module status: {status}")
        if path_string != module.replace(".", "/") + ".lean": raise ValueError(f"Module/path mismatch: {module}")
        path = safe_path(root, path_string); raw = path.read_bytes()
        if digest(raw) != row["sha256"]: raise ValueError(f"Source hash mismatch: {path_string}")
        if not set(row.get("groups", [])) <= group_ids: raise ValueError(f"Unknown group for {module}")
        if status == "finalized-machine" and (not row.get("groups") or not row.get("evidence")):
            raise ValueError(f"Finalized machine module lacks recorded evidence: {module}")
        if status in {"finalized-machine", "proved-math"} and any(memberships[g] for g in row.get("groups", [])):
            if not any(memberships[g].get(module) == row["sha256"] for g in row["groups"]):
                raise ValueError(f"Historical group membership/source hash mismatch: {module}")
        if row.get("validation", {}).get("fresh_lean_build") is not False:
            raise ValueError(f"Publication inventory must disclose no fresh Lean build: {module}")
        content = raw.decode(); bucket = digest(module.encode())[0]; snapshots[bucket][module] = content
        source_pins[path_string] = row["sha256"]
        decls = declarations(content)
        modules.append({"module": module, "path": path_string, "sha256": row["sha256"], "status": status,
                        "groups": row.get("groups", []), "scope_note": row.get("scope_note", ""),
                        "bucket": bucket, "declarations": decls, "stages": [],
                        "search": (module + " " + " ".join(d["name"] for d in decls)).lower()})
    modules.sort(key=lambda m: m["module"])
    if len({m["module"] for m in modules}) != len(modules): raise ValueError("Duplicate modules")
    expected = {p.relative_to(root).as_posix() for p in (root / "RiemannGaussian").glob("Semiprime*.lean")}
    if set(source_pins) != expected:
        raise ValueError(f"Inventory does not cover all semiprime files: missing={sorted(expected-set(source_pins))}, extra={sorted(set(source_pins)-expected)}")
    by_module = {m["module"]: m for m in modules}; stages = []; anchors = 0
    for stage in progress["stages"]:
        if stage["status"] not in STAGE_STATUSES: raise ValueError(f"Unknown stage status: {stage['status']}")
        identifier = stage["id"]
        if not re.fullmatch(r"[a-z0-9-]+", identifier): raise ValueError(f"Invalid stage id: {identifier}")
        if not set(stage.get("groups", [])) <= group_ids: raise ValueError(f"Unknown stage group: {identifier}")
        item = {**stage, "proof_anchors": [], "groups": stage.get("groups", []), "remaining": stage.get("remaining", [])}
        for anchor in stage.get("proof_anchors", []):
            if anchor["module"] not in by_module: raise ValueError(f"Missing anchor module: {anchor['module']}")
            module = by_module[anchor["module"]]; line = 1
            if anchor.get("declaration"):
                name = anchor["declaration"]
                exact = [d for d in module["declarations"] if d["name"] == name]
                matches = exact or [d for d in module["declarations"] if d["name"].endswith("." + name) or d["name"].split(".")[-1] == name]
                if len(matches) != 1: raise ValueError(f"Missing/ambiguous authored declaration: {anchor['module']}:{name}")
                line = matches[0]["line"]
            item["proof_anchors"].append({**anchor, "line": line}); anchors += 1
            if identifier not in module["stages"]: module["stages"].append(identifier)
        for module in modules:
            if set(module["groups"]) & set(item["groups"]) and identifier not in module["stages"]:
                module["stages"].append(identifier)
        stages.append(item)
    if len({s["id"] for s in stages}) != len(stages): raise ValueError("Duplicate stages")
    archived = [{**row, "local_snapshot": local_evidence.get(row.get("path"), "data/publication-inventory.json")} for row in inventory.get("archived_sources", [])]
    data = {"schema_version": 1, "metadata": meta, "stages": stages, "modules": modules, "groups": groups, "archived_sources": archived,
            "research_goal": progress["research_goal"], "full_goal_complete": False}
    compact = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    outputs[site / "data/explorer.js"] = ("window.SEMIPRIME_DATA=" + compact(data) + ";\n").encode()
    for bucket, sources in snapshots.items():
        outputs[site / f"data/sources/{bucket}.js"] = ("window.SEMIPRIME_SOURCES=" + compact(sources) + ";\n").encode()
    audit = {"schema_version": 1, "full_goal_complete": False, "research_status": "paused", "fresh_lean_build": False,
             "classification_basis": "Current source/evidence inventory; historical component gates and native integration checks retain their own scope",
             "fresh_lean_build_scope": "This generator never rebuilds Lean. Consult the linked evidence and exact release.runUrl for separate compiled validation.",
             "stage_links": "Curated reading order; not Lean-extracted proof dependencies",
             "declaration_locations": "Parsed authored source commands, not elaborated Lean names or references",
             "counts": {"modules": len(modules), "groups": len(groups), "stages": len(stages), "source_anchors": anchors,
                        "authored_source_declarations": sum(len(m["declarations"]) for m in modules)},
             "source_sha256": source_pins, "evidence_sha256": evidence,
             "input_sha256": {meta_path.relative_to(root).as_posix(): digest(meta_path.read_bytes()),
                              (packet / "inventory.json").relative_to(root).as_posix(): digest(inventory_bytes),
                              (packet / "progress.json").relative_to(root).as_posix(): digest(progress_bytes)},
             "generator_sha256": digest(Path(__file__).read_bytes()),
             "static_asset_sha256": {name: digest((site / name).read_bytes()) for name in STATIC}}
    outputs[site / "data/audit.json"] = json_bytes(audit)
    return outputs


def preview_inputs(site: Path = SITE, root: Path = ROOT):
    paths = [site / name for name in STATIC] + [site / "data/explorer.js", root / "scripts/test_semiprime_proof_explorer.py"]
    return {p.relative_to(root).as_posix(): digest(p.read_bytes()) for p in paths}


def check_preview(site: Path = SITE):
    record = site / "assets/preview.json"
    if not record.is_file(): return
    meta = json.loads(record.read_bytes())
    if meta["input_sha256"] != preview_inputs(site): raise ValueError("Stale semiprime preview; run the browser test with --refresh-preview")
    if meta["image_sha256"] != digest((site / "assets/preview.png").read_bytes()): raise ValueError("Preview image hash mismatch")
    if meta["capture"] != "Actual local Playwright Chromium screenshot": raise ValueError("Unrecognized preview provenance")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        outputs = build()
        for path, content in outputs.items():
            if args.check:
                if not path.is_file() or path.read_bytes() != content: raise ValueError(f"Stale generated asset: {path.relative_to(ROOT)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(content)
        generated = {p for p in SITE.joinpath("data").rglob("*") if p.is_file()}
        stale = generated - outputs.keys()
        if stale:
            if args.check: raise ValueError(f"Unexpected generated files: {sorted(str(p.relative_to(ROOT)) for p in stale)}")
            for obsolete in stale: obsolete.unlink()
        if args.check: check_preview()
    except (ValueError, KeyError, OSError) as error:
        print(f"Semiprime explorer validation failed: {error}", file=sys.stderr); return 1
    print(f"Semiprime explorer {'checked' if args.check else 'built'}: source/evidence hashes, authored anchors and static snapshots; no Lean build.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
