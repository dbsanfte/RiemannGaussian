"""Proof-gated discovery of signed, scale-dependent arithmetic profiles.

Legacy training observations are reused. New moment mixtures are generated by
exact linear constraints, then whole residuals select the candidates. Neither
coefficient estimates nor necessary-condition admission prove those residuals.
"""
