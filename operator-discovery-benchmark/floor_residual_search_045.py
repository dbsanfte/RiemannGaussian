TRAIN_H = OLD.TRAIN_H
FINAL_H = OLD.FINAL_H


def has_drift(weight):
    if weight['kind']=='drift_mixture':
        return True
    return weight['kind']=='product' and any(has_drift(weight[k]) for k in ('left','right'))


def drift_nodes(weight):
    if weight['kind']=='drift_mixture':
        return [weight]
    if weight['kind']=='product':
        return drift_nodes(weight['left'])+drift_nodes(weight['right'])
    return []


def baseline_recipe(recipe):
    def first(weight):
        if weight['kind']=='drift_mixture':
            return dict(kind='drift_mixture',a=weight['a'],theta=weight['theta'],
                        terms=[dict(rate=weight['terms'][0]['rate'],weight='1')])
        if weight['kind']=='product':
            return dict(kind='product',left=first(weight['left']),right=first(weight['right']))
        return deepcopy(weight)
    return dict(id='baseline_'+recipe['id'],base=first(recipe['base']),auxiliary=None)


def has_signed_auxiliary(recipe):
    return recipe['auxiliary'] is not None or any(len(node['terms'])>1 for node in drift_nodes(recipe['base']))


def grammar(legacy_recipes, meter=None):
    meter=meter or DRIFT.Meter()
    # This is an enumerated finite production budget; the APIs admit other
    # rational rates/exponents subject to work/bit guards.
    pool=sorted({Q(n,d) for d in range(1,4) for n in range(d+1,4*d+1) if n+d<=8})
    rate_sets=[(Q(1),)]
    for order,budget in ((2,3),(3,3),(4,2)):
        choices=[(Q(1),)+tail for tail in combinations(pool,order-1)]
        choices.sort(key=lambda rates:(sum(r.numerator+r.denominator for r in rates),rates))
        rate_sets.extend(choices[:budget])
    thetas=sorted({Q(n,d) for d in range(2,8) for n in range(1,d)})
    profiles=[DRIFT.synthesize_mixture([str(r) for r in rates],a,str(theta),meter)
              for a in ('1/3','1') for theta in thetas for rates in rate_sets]
    recipes=deepcopy(legacy_recipes)
    for profile in profiles:
        weights=[profile,
            dict(kind='product',left=profile,right=OLD.taper('cutoff','2/7')),
            dict(kind='product',left=profile,right=OLD.taper('log','1'))]
        for weight in weights:
            recipes.append(dict(id='drift_%04d'%(len(recipes)-len(legacy_recipes)+1),base=deepcopy(weight),auxiliary=None))
    return dict(schema='drift-floor-grammar-v1',recipes=recipes,
        legacy_family_count=len(legacy_recipes),new_family_count=len(recipes)-len(legacy_recipes),
        profile_count=len(profiles),rate_sets=[[str(r) for r in rs] for rs in rate_sets],
        theta_values=[str(t) for t in thetas],a_values=['1/3','1'],
        multipliers=list(MULTIPLIERS),b_values=list(B_VALUES),log_costs=list(OLD.LOG_COSTS),
        initial_log_etas=list(OLD.LOG_ETAS),include_proved_rate_boundary_as_eta=True,
        synthesis='exact moment constraints from enumerated rate sets; no fitted coefficients',
        proof_gates_precede_new_numerical_scores=True,root_denominators_whitelisted=False,
        fitted_per_N=False,anticipated_winner=None,generation_counts=meter.counts())


def weight_limit(weight, cache, meter):
    if weight['kind']=='drift_mixture':
        key=OLD.ast_key(weight)
        if key not in cache:
            certificate=DRIFT.mixture_certificate(weight,meter)
            verified=DRIFT_CHECK.verify_certificate(weight,certificate)
            cache[key]=dict(certificate=certificate,verification=verified)
        return dict(limit='1',bound='sum_abs_weights',proof=cache[key],fixed_index_only=True,
                    global_norm_bound_proved=False)
    if weight['kind']=='product':
        return dict(limit='1',rule='product_of_bounded_limit_one_weights',
                    premises=[weight_limit(weight[k],cache,meter) for k in ('left','right')],
                    fixed_index_only=True,global_norm_bound_proved=False)
    return OLD.weight_limit(weight)


def weight_correction(weight,n,cache,meter):
    if weight['kind']=='drift_mixture':
        key=OLD.ast_key(weight)
        if key not in cache:
            raise ValueError('drift moment certificate must be independently admitted first')
        cert=cache[key]
        return RATE._leading(Q(cert['coefficient_rate']),[dict(
            rational=str(-Q(cert['leading_error_coefficient']['rational'])),
            log_n_power=cert['leading_error_coefficient']['log_n_power'],log_2_power='0')],n,
            'signed moment cancellation and rational drift ceiling; dyadic error is log-flat')
    if weight['kind']=='product':
        return RATE.combine([weight_correction(weight[k],n,cache,meter) for k in ('left','right')],n,
                            'product corrections add at first nonzero order')
    return RATE.weight_correction(weight,n,meter)


def candidate_rows(recipe,witnesses,cache,meter,checker_meter,max_index=16):
    rows=[]
    for n in range(2,max_index+1):
        if n not in witnesses:
            witnesses[n]=RATE.generate_witness(n,meter)
        if not has_drift(recipe['base']):
            error=RATE.coefficient_error(recipe,n,meter)
        else:
            if recipe['auxiliary'] is not None:
                raise ValueError('new drift auxiliary must be represented inside the signed profile')
            mu=RATE.mobius(n,meter)
            expansion=RATE._scale(weight_correction(recipe['base'],n,cache,meter),Q(-mu))
            error=dict(index=n,mu=mu,auxiliary_arithmetic=None,expansion=expansion,
                       coefficient_limit_is_compatible=True)
        e=error['expansion']
        license=RATE.license_nonzero(e['coefficient'],n,192,meter) if e['status']=='leading' else None
        status='certified_rate_obstruction' if license and license['status']=='certified' else ('OPEN' if e['status']=='flat' else 'UNRESOLVED')
        row=dict(**error,status=status,nonzero_license=license,witness=witnesses[n],
                 energy_rate=str(2*Q(e['rate'])) if status=='certified_rate_obstruction' else None,
                 asymptotic_norm_lower='liminf L^(2*nu)*norm_squared >= leading_coefficient^2/witness.denominator' if status=='certified_rate_obstruction' else None)
        DRIFT_CHECK.verify_rate_candidate(recipe,n,row,precision=192,meter=checker_meter)
        rows.append(row)
    return rows


def dyadic(pair):
    a,e=int(pair[0]),pair[1]
    return Q(a<<e) if e>=0 else Q(a,1<<(-e))


def forcing_witnesses(rows,q,b):
    result=[]
    for row in rows:
        response=sum(Q(cell['alpha']) for cell in row['witness']['cells'] if cell['k']>=q)
        if row['energy_rate'] is not None and (Q(b)==0 or (row['index']%q!=0 and response==0)):
            result.append(row)
    return result


def reject_bound(witnesses,A,eta):
    for row in witnesses:
        rate=Q(row['energy_rate'])
        if Q(eta)>rate:
            return dict(index=row['index'],reason='strict_log_rate',energy_rate=str(rate))
        enclosure=row['nonzero_license']['enclosure']
        if Q(eta)==rate and enclosure is not None:
            lo,hi=dyadic(enclosure['lower_dyadic']),dyadic(enclosure['upper_dyadic'])
            absolute=Q(0) if lo<=0<=hi else min(abs(lo),abs(hi))
            constant=absolute**2/Q(row['witness']['denominator'])
            if Q(A)<constant:
                return dict(index=row['index'],reason='strict_boundary_constant',energy_rate=str(rate),
                            certified_lower_constant=str(constant))
    return None


def proof_gates(frozen_grammar,progress=None):
    meter=RATE.Meter(cap=150_000_000,seconds=3600)
    checker_meter=DRIFT_CHECK.Meter(cap=300_000_000)
    drift_meter=DRIFT.Meter(cap=100_000_000,seconds=3600)
    cutoff_meter,cutoff_checker=CUTOFF.Meter(max_operations=5_000_000,seconds=3600),CUTOFF.Meter(max_operations=5_000_000,seconds=3600)
    witnesses,cache={},{}
    families,admissions=[],[]
    for i,recipe in enumerate(frozen_grammar['recipes'],1):
        for node in drift_nodes(recipe['base']):
            key=OLD.ast_key(node)
            if key not in cache:
                cert=DRIFT.mixture_certificate(node,drift_meter)
                DRIFT_CHECK.verify_certificate(node,cert,meter=checker_meter)
                cache[key]=cert
        rows=candidate_rows(recipe,witnesses,cache,meter,checker_meter)
        families.append(dict(recipe=recipe,candidates=rows,independently_replayed=True,
                             convergence_proved=False))
        for q in MULTIPLIERS:
            for b in B_VALUES:
                eligible=forcing_witnesses(rows,q,b)
                etas=sorted({Q(e) for e in frozen_grammar['initial_log_etas']} |
                            {Q(r['energy_rate']) for r in eligible if Q(r['energy_rate'])<=1},reverse=True)
                request=dict(recipe=recipe,q=q,b=b,domain=dict(kind='all_integer',minimum=min(FINAL_PARENTS)),
                             rounding=deepcopy(CUTOFF.ROUNDING))
                cutoff=CUTOFF.build_guard(request,meter=cutoff_meter)
                verified=None
                if cutoff['status']==CUTOFF.REFUTED:
                    verified=CUTOFF.verify_guard(request,cutoff,meter=cutoff_checker)
                admitted,rejected=[],[]
                for eta in etas:
                    for A in frozen_grammar['log_costs']:
                        why=reject_bound(eligible,A,str(eta))
                        if cutoff['status']==CUTOFF.REFUTED:
                            why=dict(reason='fixed_cutoff_all_integer_obstruction')
                        entry=dict(A=A,eta=str(eta))
                        (rejected if why else admitted).append(dict(**entry,reason=why) if why else entry)
                admissions.append(dict(family=recipe['id'],q=q,b=b,admitted_bounds=admitted,
                    rejected_bounds=rejected,cutoff_certificate=cutoff,cutoff_verification=verified,
                    eligible_witness_indices=[r['index'] for r in eligible],
                    admitted_means_not_refuted_by_these_gates=True,uniform_upper_bound_proved=False))
        if progress and (i%100==0 or i==len(frozen_grammar['recipes'])):
            progress('proof_gate_progress',families=i,total=len(frozen_grammar['recipes']))
    return dict(schema='drift-presearch-gates-v1',families=families,admissions=admissions,
        all_before_new_scores=True,formula_count=len(families),rule_count=len(admissions),
        entirely_refuted_rules=sum(not a['admitted_bounds'] for a in admissions),
        rejected_bound_pairs=sum(len(a['rejected_bounds']) for a in admissions),
        producer_operations=meter.operations,checker_operations=checker_meter.operations,
        drift_certificate_operations=drift_meter.operations,
        cutoff_operations=cutoff_meter.operations,cutoff_replay_operations=cutoff_checker.operations,
        uniform_upper_bound_proved=False,RH_proved=False)


class Compiler(OLD.Compiler):
    def __init__(self,maximum,meter=None,drift_meter=None,retain_compilation_certificates=True):
        super().__init__(maximum,meter)
        self.drift_meter=drift_meter or DRIFT.Meter(cap=5_000_000_000,seconds=3600)
        self.drift=DRIFT.DriftCompiler(meter=self.drift_meter)
        self.retain_compilation_certificates=retain_compilation_certificates

    def weights_at(self,weight,N):
        key=(OLD.ast_key(weight),N)
        if key in self.weights:
            return self.weights[key]
        if weight['kind']=='drift_mixture':
            values=list(self.drift.profile(weight,N))
            if not self.retain_compilation_certificates:
                # Training needs exact values; final source replay retains the
                # full per-index certificates in its separate compiler.
                self.drift.context(weight,N).cache.clear()
        elif weight['kind']=='product' and has_drift(weight):
            values=[a*b for a,b in zip(self.weights_at(weight['left'],N),self.weights_at(weight['right'],N))]
        else:
            return super().weights_at(weight,N)
        self.meter.charge(12*N)
        self.weights[key]=values
        return values

    def compile(self,recipe,N):
        if not has_drift(recipe['base']):
            return super().compile(recipe,N)
        if recipe['auxiliary'] is not None or type(N) is not int or not 2<=N<=self.maximum:
            raise ValueError('typed finite drift recipe')
        values=self.weights_at(recipe['base'],N)
        self.meter.charge(24*N)
        return OLD.program(recipe['id']+'_N'+str(N),{n:-self.channels['mu'][n]*w for n,w in enumerate(values,2)})


class CachedNorms:
    """Price identical exact vectors once across different formula ASTs."""
    def __init__(self,norms):
        self.norms,self.values,self.hits,self.misses=norms,{},0,0

    def price(self,programs):
        keys=[OLD.semantic_key(p) for p in programs]
        fresh={}
        for key,p in zip(keys,programs):
            self.norms.meter.charge(4*(len(p['coefficients'])+len(p['steps'])+1))
            if key in self.values or key in fresh:self.hits+=1
            else:fresh[key]=p
        priced=self.norms.price(list(fresh.values())) if fresh else []
        self.values.update(zip(fresh,priced));self.misses+=len(fresh)
        return [self.values[key] for key in keys]


def assess(recipe,q,b,observations,admission):
    bounds=[bound for bound in admission['admitted_bounds'] if all(
        o['forcing']['ranking_upper_proxy']<=float(Q(bound['A']))/o['N'].bit_length()**float(Q(bound['eta']))
        for o in observations)]
    bound=bounds[0] if bounds else None
    for o in observations:
        threshold=float(Q(bound['A']))/o['N'].bit_length()**float(Q(bound['eta'])) if bound else -1
        o['auxiliary_cross']=OLD.cross_diagnostic(o['forcing'],o['baseline_forcing'],o['auxiliary_forcing'],threshold)
        o['refinement_cross']=OLD.cross_diagnostic(o['forcing'],o['child'],OLD.scale_norm(o['parent'],float(Q(b)**2/q)),threshold)
    return dict(family=recipe['id'],q=q,b=b,has_auxiliary=has_signed_auxiliary(recipe),has_drift=has_drift(recipe['base']),
        maximum_mixture_order=max((len(n['terms']) for n in drift_nodes(recipe['base'])),default=0),
        observations=observations,finite_log_bound=bound,
        fallback_bound=admission['admitted_bounds'][-1] if admission['admitted_bounds'] else None,
        auxiliary_signed_needed_count=sum(o['auxiliary_cross']['signed_needed_proxy'] for o in observations),
        refinement_signed_needed_count=sum(o['refinement_cross']['signed_needed_proxy'] for o in observations),
        worst_forcing_log_power=OLD.log_slope([o['forcing']['ranking_upper_proxy'] for o in observations]),
        worst_target_log_power=OLD.log_slope([o['child']['ranking_upper_proxy'] for o in observations]),
        endpoint_restatement=b=='0',uniform_inequality_proved=False)


def select(assessments,parents=TRAIN_PARENTS):
    if tuple(parents)!=TRAIN_PARENTS or any([o['N'] for o in r['observations']]!=list(parents) for r in assessments):
        raise ValueError('selection requires only registered training parents')
    if len({(r['family'],r['q'],r['b']) for r in assessments})!=len(assessments):
        raise ValueError('duplicate scored rule')
    def rank(row):
        bound=row['finite_log_bound']
        return (bound is None,-float(Q(bound['eta'])) if bound else 0,
            -row['auxiliary_signed_needed_count'],-row['refinement_signed_needed_count'],
            row['worst_forcing_log_power'],row['worst_target_log_power'],
            row['observations'][-1]['forcing']['ranking_upper_proxy'],row['family'],row['q'],row['b'])
    strata=[('signed_drift',lambda r:r['has_drift'] and r['maximum_mixture_order']>=2 and r['b']!='0'),
            ('second_drift_family',lambda r:r['has_drift'] and r['b']!='0'),
            ('legacy_control',lambda r:not r['has_drift'] and r['b']!='0'),
            ('endpoint_restatement_control',lambda r:r['b']=='0')]
    used,used_drift_families,chosen=set(),set(),[]
    for name,condition in strata:
        candidates=[r for r in assessments if condition(r) and r['fallback_bound'] is not None and
                    (r['family'],r['q'],r['b']) not in used and
                    (name!='second_drift_family' or r['family'] not in used_drift_families)]
        if not candidates:
            raise ValueError('no admitted rule in registered selection stratum '+name)
        row=min(candidates,key=rank)
        used.add((row['family'],row['q'],row['b']))
        if row['has_drift']:used_drift_families.add(row['family'])
        chosen.append(dict(stratum=name,family=row['family'],q=row['q'],b=row['b'],
            finite_log_bound=row['finite_log_bound'],audit_log_bound=row['finite_log_bound'] or row['fallback_bound'],
            auxiliary_signed_needed_training=row['auxiliary_signed_needed_count'],
            refinement_signed_needed_training=row['refinement_signed_needed_count'],
            proof_gates_passed_as_necessary_conditions_only=True))
    return chosen


def search(frozen_grammar,gates,legacy_search,progress=None):
    recipes=frozen_grammar['recipes'];by_id={r['id']:r for r in recipes}
    if len(by_id)!=len(recipes):raise ValueError('unique formula identifiers')
    if ([f['recipe'] for f in gates['families']]!=recipes or
        any(f.get('independently_replayed') is not True for f in gates['families']) or
        gates.get('all_before_new_scores') is not True):
        raise ValueError('complete source-bound proof admission must precede scores')
    admissions={(a['family'],a['q'],a['b']):a for a in gates['admissions']}
    expected={(r['id'],q,b) for r in recipes for q in MULTIPLIERS for b in B_VALUES}
    if set(admissions)!=expected or len(admissions)!=len(gates['admissions']):raise ValueError('complete presearch gates')
    if legacy_search['training_parents']!=list(TRAIN_PARENTS) or legacy_search['training_H']!=TRAIN_H:
        raise ValueError('unchanged legacy training partition/estimator')
    legacy_ids={r['id'] for r in recipes[:frozen_grammar['legacy_family_count']]}
    legacy_rows=legacy_search['assessments']
    if {(r['family'],r['q'],r['b']) for r in legacy_rows}!={(r,q,b) for r in legacy_ids for q in MULTIPLIERS for b in B_VALUES}:
        raise ValueError('complete legacy training data')
    assessments=[]
    for row in legacy_rows:
        key=row['family'],row['q'],row['b']
        if admissions[key]['admitted_bounds']:
            assessments.append(assess(by_id[row['family']],row['q'],row['b'],deepcopy(row['observations']),admissions[key]))
    meter=OLD.Meter(cap=300_000_000_000,seconds=3600)
    compiler=Compiler(max(TRAIN_PARENTS)*max(MULTIPLIERS),meter,retain_compilation_certificates=False)
    norms=CachedNorms(OLD.TrainingNorms(compiler.maximum,TRAIN_H,meter))
    supports=sorted(set(TRAIN_PARENTS)|{q*N for q in MULTIPLIERS for N in TRAIN_PARENTS})
    baselines={}
    new_recipes=recipes[frozen_grammar['legacy_family_count']:]
    for index,recipe in enumerate(new_recipes,1):
        keys=[(q,b,N) for q in MULTIPLIERS for b in B_VALUES if admissions[(recipe['id'],q,b)]['admitted_bounds'] for N in TRAIN_PARENTS]
        if not keys:continue
        base=baseline_recipe(recipe);base_key=OLD.ast_key(base['base'])
        if base_key not in baselines:
            targets0={N:compiler.compile(base,N) for N in supports}
            h0={(q,b,N):OLD.forcing_program(targets0[N],targets0[q*N],q,b)
                for q in MULTIPLIERS for b in B_VALUES for N in TRAIN_PARENTS}
            baselines[base_key]=(h0,dict(zip(h0,norms.price(list(h0.values())))))
        h0,prices0=baselines[base_key]
        targets={N:compiler.compile(recipe,N) for N in supports}
        h={key:OLD.forcing_program(targets[key[2]],targets[key[0]*key[2]],key[0],key[1]) for key in keys}
        v={key:OLD.difference_program(p,h0[key],p['id']+'_mixture_aux') for key,p in h.items()}
        distinct={}
        for p in list(targets.values())+list(h.values())+list(v.values()):distinct.setdefault(OLD.semantic_key(p),p)
        prices=dict(zip(distinct,norms.price(list(distinct.values()))))
        for q in MULTIPLIERS:
            for b in B_VALUES:
                admission=admissions[(recipe['id'],q,b)]
                if not admission['admitted_bounds']:continue
                observations=[dict(N=N,parent=prices[OLD.semantic_key(targets[N])],child=prices[OLD.semantic_key(targets[q*N])],
                    forcing=prices[OLD.semantic_key(h[(q,b,N)])],baseline_forcing=prices0[(q,b,N)],
                    auxiliary_forcing=prices[OLD.semantic_key(v[(q,b,N)])]) for N in TRAIN_PARENTS]
                assessments.append(assess(recipe,q,b,observations,admission))
        if progress and (index%50==0 or index==len(new_recipes)):
            progress('new_training_progress',families=index,total=len(new_recipes),operations=meter.operations,
                     drift_operations=compiler.drift_meter.operations)
    choices=select(assessments)
    return dict(schema='proof-gated-drift-search-v1',assessments=assessments,selections=choices,
        selected_recipes=[by_id[id] for id in sorted({c['family'] for c in choices})],
        family_count=len(recipes),scored_rule_count=len(assessments),legacy_training_rows_reused=len(legacy_rows),
        old_training_norms_recomputed=0,training_parents=list(TRAIN_PARENTS),training_H=TRAIN_H,
        finite_log_bound_matches=sum(r['finite_log_bound'] is not None for r in assessments),
        auxiliary_signed_needed_matches=sum(r['auxiliary_signed_needed_count']>0 for r in assessments),
        refinement_signed_needed_matches=sum(r['refinement_signed_needed_count']>0 for r in assessments),
        final_observations_used_in_selection=False,counts=meter.counts(),drift_counts=compiler.drift_meter.counts(),
        exact_vector_price_cache_hits=norms.hits,distinct_new_training_vectors=norms.misses,
        uniform_inequality_proved=False,RH_proved=False)
