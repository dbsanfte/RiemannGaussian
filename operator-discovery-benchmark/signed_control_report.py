#!/usr/bin/env python3
"""Report signed arithmetic control and its actual RH proof obligations."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

BASE=Path(__file__).resolve().parent


def read(path): return json.loads(Path(path).read_text())
def sha(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def digest(value): return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(",", ":"),allow_nan=False).encode()).hexdigest()


def summary(directory):
    directory=Path(directory).resolve(); spec=read(directory/"protocol.json"); audit=read(directory/"verification.json")
    seal=read(directory/"seal.json"); archive=read(directory/"archive.json"); final=read(directory/"final_evaluation.json")
    assert audit["all_passed"] and all(audit["checks"].values())
    assert audit["source_final_sha256"]==sha(directory/"final_evaluation.json")
    assert audit["protocol_sha256"]==digest(spec) and final["seal_sha256"]==digest(seal)
    assert audit["checker_code_sha256"]==sha(BASE/"check_signed_control.py") and audit["proof_sha256"]==sha(BASE/"signed_control_proof.txt")
    for name,expected in spec["code_sha256"].items(): assert sha(BASE/name)==expected
    for name,expected in seal["files"].items(): assert sha(directory/name)==expected
    cases=read(directory/"final_cases.json"); assert final["final_cases_sha256"]==digest(cases)
    assert not spec["historical_priority_is_acceptance_gate"] and not archive["historical_priority_used"]
    batch=read(directory/"candidate_batch.json"); records=read(directory/"validation_data.json")["records"]
    statuses=Counter(e["status"] for r in records for e in r["estimates"])
    finite_success=sum(r["finite_validation_passed"] for row in final["records"] for r in row["estimate_outcomes"])
    return {"status":"independently_verified_signed_control_discovery_pilot", "run_directory":str(directory),
            "objective":spec["objective"],"historical_priority_is_acceptance_gate":False,
            "programs_generated":len(batch["programs"]),"generation_rejections":len(batch["rejected"]),
            "development_estimate_statuses":dict(statuses),"operators_archived":len(archive["archive"]),
            "complete_final_estimates":sum(len(r["estimate_outcomes"]) for r in final["records"]),
            "complete_final_estimates_passing_finite_windows":finite_success,"checks":audit["checks"],
            "independent_complete_inverse_coefficients":audit["independent_complete_inverse_coefficients"],
            "independent_complete_moment_values":audit["independent_complete_moment_values"],
            "final_cases":cases["scales"],"archive":[r["program"] for r in archive["archive"]],
            "verified_all_scale_operator_properties":["signed linear scale recurrence", "uniform Lipschitz constant",
                  "all-height nonvanishing multiplier Re(s)>=1/2", "bounded inverse for the certified weighted norm"],
            "conditional_control_template":"uniform residual moment bound -> pointwise signed bound -> zero exclusion; constants and inverse costs explicit",
            "RH_completion_obligation":"independently prove uniform moment premises at exponents beta_q/(q+1) approaching 1/2, or another RH-sufficient signed estimate",
            "uniform_sublinear_signed_controls_verified":[],"RH_proved":False,
            "historical_novelty_established":"not required for mathematical acceptance",
            "verification_sha256":sha(directory/"verification.json"),"protocol_sha256":digest(spec)}


def publish(directory):
    directory=Path(directory).resolve(); result=summary(directory)
    text=f"""SIGNED ARITHMETIC CONTROL SEARCH

Objective: {result['objective']}.
Historical priority is an annotation, not an acceptance gate.

Generated {result['programs_generated']} scale operators from actual Mobius
data; retained {result['operators_archived']} under frozen selection rules.
Coefficients are learned by exact weighted least squares or generated by
signed rational exploration, then projected into a certified invertible
critical-weight domain. No prime oracle or nominated answer is used.
Inference fits moment exponents from data, with declared rounding and costs.

Development observations are sampled unit-cell estimates. Final evaluation
uses every unit interval of fresh windows after archive sealing. Independent
verification uses a prime sieve for coefficients, an alternative homogeneous
moment recurrence, and a fresh actual-zeta zero disk.

Independent checks: {sum(result['checks'].values())}/{len(result['checks'])}.
Full arithmetic prefix: {result['independent_complete_inverse_coefficients']} coefficients.
Exact complete moment values checked: {result['independent_complete_moment_values']}.
Finite final estimates passed: {result['complete_final_estimates_passing_finite_windows']}/{result['complete_final_estimates']}.
Final window scales: {result['final_cases']}.

Development estimate statuses:
{json.dumps(result['development_estimate_statuses'],indent=2)}

Verified operator and transfer properties apply at every scale. Each archived
operator has an all-height nonvanishing ordinary-zeta multiplier and explicit
inverse cost. Historical novelty does not affect acceptance. A bounded
Dirichlet-floor cancellation that erases zeta-zero poles is rejected as an RH
control, although its all-scale arithmetic identity is true.

The missing step is a UNIFORM SIGNED MOMENT ESTIMATE. No sublinear uniform
premise is proved by this pilot. A fitted constant and exponent remain leads
even after all finite windows pass. Their conditional transport certificate
states exactly the all-scale bound needed to exclude ordinary zeta zeros.
For RH, a finite list of moment orders is insufficient: the resulting pointwise
exponents must approach 1/2 under independently proved uniform premises.

Archived programs and universal costs:
{json.dumps(result['archive'],indent=2)}

Proof: signed_control_proof.txt. Detailed numerical obligations: archive.json
and final_evaluation.json. Neither a smaller residual nor a positive moment
by itself proves cancellation at all scales. RH remains unproved.
"""
    (directory/"summary.json").write_text(json.dumps(result,indent=2)+"\n")
    (directory/"report.txt").write_text(text)
    pointer=BASE/"signed-control-results/latest.json"; pointer.parent.mkdir(exist_ok=True)
    pointer.write_text(json.dumps({"run_directory":str(directory),"summary_sha256":digest(result)},indent=2)+"\n")
    return result


def load_latest():
    path=BASE/"signed-control-results/latest.json"
    if not path.exists(): return {"status":"not_run","uniform_sublinear_signed_controls_verified":[],"RH_proved":False}
    pointer=read(path); result=summary(pointer["run_directory"])
    assert digest(result)==pointer["summary_sha256"]
    return result


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument("--run-dir",type=Path,required=True)
    args=parser.parse_args(); result=publish(args.run_dir)
    print("Published signed-control pilot",result["operators_archived"],"operators; uniform sublinear premises remain open")
